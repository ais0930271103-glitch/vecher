CITY_INDEX: dict[str, tuple[str, str, str]] = {c[0].lower().replace("ё", "е"): c for c in CITIES}


def find_city(name: str) -> tuple[str, str, str] | None:
    return CITY_INDEX.get(name.strip().lower().replace("ё", "е"))


def search_cities(q: str, limit: int = 20) -> list[tuple[str, str, str]]:
    key = q.strip().lower().replace("ё", "е")
    if not key:
        return CITIES[:limit]
    starts = [c for c in CITIES if c[0].lower().replace("ё", "е").startswith(key)]
    contains = [c for c in CITIES if c not in starts and key in c[0].lower().replace("ё", "е")]
    return (starts + contains)[:limit]
